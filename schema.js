export const schemaSql = `CREATE TABLE IF NOT EXISTS sounds (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL, city TEXT NOT NULL,
      district TEXT NOT NULL, mood TEXT NOT NULL, lat REAL NOT NULL, lng REAL NOT NULL,
      duration INTEGER NOT NULL, color TEXT NOT NULL, description TEXT NOT NULL,
      frequency INTEGER NOT NULL, texture TEXT NOT NULL, recorded_at TEXT NOT NULL);
      CREATE TABLE IF NOT EXISTS field_notes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sound_id INTEGER NOT NULL REFERENCES sounds(id),
        author TEXT NOT NULL, note TEXT NOT NULL, created_at TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'approved');
      CREATE TABLE IF NOT EXISTS request_budgets(key TEXT PRIMARY KEY,count INTEGER NOT NULL,reset_at BIGINT NOT NULL);
      CREATE TABLE IF NOT EXISTS user_recordings(sound_id INTEGER PRIMARY KEY REFERENCES sounds(id),owner_id TEXT NOT NULL,
        file TEXT NOT NULL UNIQUE,status TEXT NOT NULL DEFAULT 'pending',size INTEGER NOT NULL,created_at TEXT NOT NULL);`;
